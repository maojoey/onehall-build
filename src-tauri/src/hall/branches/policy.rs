//! Audited workspace commands from web/router.rs. Deliberately static: a new
//! upstream endpoint does not automatically gain headquarters relay access.
//! Credentials/auth, server administration, backups, sync and hall management
//! are absent. Browser/Office HTML needs a separate isolated origin.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Kind {
    Json,
    Upload,
    Download,
    Ticket,
}
pub(super) fn classify(command: &str) -> Option<Kind> {
    match command {
        "upload_attachment" | "upload_workspace_file" => Some(Kind::Upload),
        "download_workspace_file" | "download_workspace_dir" => Some(Kind::Download),
        "workspace_download_ticket" => Some(Kind::Ticket),
        _ if JSON_COMMANDS.contains(&command) => Some(Kind::Json),
        _ => None,
    }
}
pub(super) fn isolated_preview(command: &str) -> bool {
    command.starts_with("browser_bridge_")
        || command.contains("office_watch")
        || command == "officecli_render_html"
}
