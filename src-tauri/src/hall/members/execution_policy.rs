//! How a member's agent is started and what the host can honestly claim about
//! it. The policy only decides; Hall keeps owning review, run identity, exit
//! domains and permission waits. Nothing here probes the system, so a
//! capability is `verified` only when a recorded evidence entry matches the
//! exact engine, adapter, mode and platform. Simulated tests never count.
use super::config::LaunchProfile;
use crate::app_error::AppCommandError;
use serde::{Deserialize, Serialize};

/// Host-private marker carried in the launch environment so the connection
/// manager follows this policy instead of branching on an engine name. The
/// manager removes it before the agent process environment is built.
pub(crate) const MODE_ENV: &str = "ONEHALL_EXECUTION_MODE";

pub(crate) const CODEX_ENGINE_VERSION: &str = super::codex_bridge::SUPPORTED_VERSION;
pub(crate) const CODEX_ADAPTER_VERSION: &str = "codex-acp 2.2.2";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ExecutionMode {
    Restricted,
    LocalAssistant,
}

impl ExecutionMode {
    fn marker(self) -> &'static str {
        match self {
            Self::Restricted => "restricted",
            Self::LocalAssistant => "local_assistant",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Enforcement {
    Verified,
    NotEnforced,
    Unknown,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PermissionRequests {
    Supported,
    Unsupported,
    Unknown,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ExitCoverage {
    LinuxCgroupV2,
    WindowsJobObject,
    MacosProcessGroupBestEffort,
    Unknown,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Platform {
    Linux,
    Windows,
    Macos,
    Other,
}

impl Platform {
    pub(crate) fn current() -> Self {
        if cfg!(target_os = "linux") {
            Self::Linux
        } else if cfg!(windows) {
            Self::Windows
        } else if cfg!(target_os = "macos") {
            Self::Macos
        } else {
            Self::Other
        }
    }
    fn exit_coverage(self) -> ExitCoverage {
        match self {
            Self::Linux => ExitCoverage::LinuxCgroupV2,
            Self::Windows => ExitCoverage::WindowsJobObject,
            Self::Macos => ExitCoverage::MacosProcessGroupBestEffort,
            Self::Other => ExitCoverage::Unknown,
        }
    }
}

/// Generated by the host only. Deserialization exists for the stored snapshot,
/// which `consistent` checks again; a client never supplies these values.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ExecutionCapabilities {
    pub read_boundary: Enforcement,
    pub write_boundary: Enforcement,
    pub network_boundary: Enforcement,
    pub permission_requests: PermissionRequests,
    pub hall_identity: bool,
    pub hall_report: bool,
    pub exit_coverage: ExitCoverage,
    pub engine_version: Option<String>,
    pub adapter_version: Option<String>,
    pub evidence_id: Option<String>,
}

/// One recorded real-system verification of a restricted combination.
pub(crate) struct Evidence {
    pub id: &'static str,
    pub engine: &'static str,
    pub platform: Platform,
    pub engine_version: &'static str,
    pub adapter_version: &'static str,
    pub read: Enforcement,
    pub write: Enforcement,
    pub network: Enforcement,
}

/// Empty until a real native run (package 08) is recorded. Until then every
/// restricted boundary reports `unknown`.
pub(crate) const EVIDENCE: &[Evidence] = &[];

/// The mode that governs a member whose declaration did not choose one:
/// Codex always ran restricted; legacy Claude has no recorded mode.
pub(crate) fn effective_mode(
    engine: &str,
    declared: Option<ExecutionMode>,
) -> Option<ExecutionMode> {
    declared.or((engine == "codex").then_some(ExecutionMode::Restricted))
}

fn versions(engine: &str, mode: Option<ExecutionMode>) -> (Option<String>, Option<String>) {
    if engine == "codex" && mode == Some(ExecutionMode::Restricted) {
        (
            Some(CODEX_ENGINE_VERSION.to_owned()),
            Some(CODEX_ADAPTER_VERSION.to_owned()),
        )
    } else {
        (None, None)
    }
}

pub(crate) fn capabilities(
    engine: &str,
    mode: Option<ExecutionMode>,
    platform: Platform,
) -> ExecutionCapabilities {
    capabilities_with(engine, mode, platform, EVIDENCE)
}

pub(crate) fn capabilities_with(
    engine: &str,
    mode: Option<ExecutionMode>,
    platform: Platform,
    evidence: &[Evidence],
) -> ExecutionCapabilities {
    let (engine_version, adapter_version) = versions(engine, mode);
    let found = evidence.iter().find(|e| {
        mode == Some(ExecutionMode::Restricted)
            && e.engine == engine
            && e.platform == platform
            && engine_version.as_deref() == Some(e.engine_version)
            && adapter_version.as_deref() == Some(e.adapter_version)
    });
    let (read, write, network) = match (mode, found) {
        (_, Some(e)) => (e.read, e.write, e.network),
        (Some(ExecutionMode::LocalAssistant), None) => (
            Enforcement::NotEnforced,
            Enforcement::NotEnforced,
            Enforcement::NotEnforced,
        ),
        _ => (
            Enforcement::Unknown,
            Enforcement::Unknown,
            Enforcement::Unknown,
        ),
    };
    ExecutionCapabilities {
        read_boundary: read,
        write_boundary: write,
        network_boundary: network,
        permission_requests: if mode.is_some() {
            PermissionRequests::Supported
        } else {
            PermissionRequests::Unknown
        },
        hall_identity: true,
        hall_report: true,
        exit_coverage: platform.exit_coverage(),
        engine_version,
        adapter_version,
        evidence_id: found.map(|e| e.id.to_owned()),
    }
}

/// Rejects forged or impossible stored claims without depending on the host
/// that restores the snapshot.
pub(crate) fn consistent(engine: &str, mode: ExecutionMode, caps: &ExecutionCapabilities) -> bool {
    if !caps.hall_identity || !caps.hall_report {
        return false;
    }
    let boundaries = [
        caps.read_boundary,
        caps.write_boundary,
        caps.network_boundary,
    ];
    let (engine_version, adapter_version) = versions(engine, Some(mode));
    if caps.engine_version != engine_version || caps.adapter_version != adapter_version {
        return false;
    }
    match mode {
        ExecutionMode::LocalAssistant => {
            caps.evidence_id.is_none() && boundaries.iter().all(|b| *b == Enforcement::NotEnforced)
        }
        ExecutionMode::Restricted => {
            if boundaries.contains(&Enforcement::NotEnforced) {
                return false;
            }
            match &caps.evidence_id {
                None => boundaries.iter().all(|b| *b == Enforcement::Unknown),
                Some(id) => EVIDENCE.iter().any(|e| {
                    e.id == id && e.engine == engine && boundaries == [e.read, e.write, e.network]
                }),
            }
        }
    }
}

/// What the launch does for one member. Pure: no file, process or database
/// access, so a refusal happens before any side effect.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct Decision {
    pub mode: Option<ExecutionMode>,
    /// Codex runs through the frozen permission bridge.
    pub bridge: bool,
    /// The member's own read-only OneDesk key may be handed to the process.
    pub key: bool,
}

fn refuse(message: &str) -> AppCommandError {
    AppCommandError::invalid_input(message.to_owned())
}

pub(crate) fn decide(
    profile: &LaunchProfile,
    platform: Platform,
) -> Result<Decision, AppCommandError> {
    let mode = effective_mode(&profile.engine, profile.execution_mode);
    match mode {
        Some(ExecutionMode::Restricted) => {
            if profile.engine != "codex" {
                return Err(refuse("Restricted execution is only available for Codex"));
            }
            if platform == Platform::Windows {
                return Err(refuse(
                    "Restricted Codex execution is not available on Windows; \
                     save a local assistant snapshot to run here",
                ));
            }
        }
        Some(ExecutionMode::LocalAssistant) if profile.access.onedesk_key != "none" => {
            return Err(refuse("A local assistant never receives the OneDesk key"));
        }
        Some(ExecutionMode::LocalAssistant) => {}
        None => {}
    }
    if let Some(frozen) = &profile.capabilities {
        let mode = mode.ok_or_else(|| refuse("Execution snapshot has no execution mode"))?;
        if *frozen != capabilities(&profile.engine, Some(mode), platform) {
            return Err(refuse(
                "Execution capabilities changed; run preflight and save a new snapshot",
            ));
        }
    }
    Ok(Decision {
        mode,
        bridge: mode == Some(ExecutionMode::Restricted) && profile.engine == "codex",
        key: mode != Some(ExecutionMode::LocalAssistant),
    })
}

/// Host-only start preflight for this machine; no file, process or model side
/// effect, so a refusal leaves nothing to clean up.
pub(crate) fn check_start(profile: &LaunchProfile) -> Result<(), AppCommandError> {
    check_start_on(profile, Platform::current())
}

pub(crate) fn check_start_on(
    profile: &LaunchProfile,
    platform: Platform,
) -> Result<(), AppCommandError> {
    decide(profile, platform).map(|_| ())
}

/// Value for [`MODE_ENV`]; `legacy` for a member that never chose a mode.
pub(crate) fn marker(decision: &Decision) -> &'static str {
    decision.mode.map_or("legacy", ExecutionMode::marker)
}

/// Whether the manager must see a frozen Codex permission config. Anything
/// but an explicit local assistant keeps the existing requirement.
pub(crate) fn bridge_required(marker: Option<&str>) -> bool {
    marker != Some(ExecutionMode::LocalAssistant.marker())
}

